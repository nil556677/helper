"""切分器与语义兜底**共享的常量**（放在这里避免子模块之间循环 import）。

## 在流水线中的位置

解析（P1.1）→ 结构识别（P1.2）→ **切分（P1.3，本包）** → 入库（P1.4）。
本模块不参与计算，只提供"切分口径"的常量：token 换算、标点集合、比例阈值。

## 输入 / 输出

- 输入：无（纯常量）。
- 输出：被 ``sentences`` / ``derived`` / ``estimate`` / ``semantic`` 等子模块 import。

## 关键约定

1. **标点按"全角 + 半角"双写**：中英文文档都可能出现，漏一个就会在那种文档上退化成硬切；
2. **``TOKENS_PER_CHAR`` 只是兜底**：拿得到 bge-m3 分词器时不用它（见 ``estimate``），
   所以别把它当"准确的换算率"；
3. 句末/续句/收尾/成对符号的**语义**由 ``sentences`` 解释，改这里等于改切分行为。
"""

#: token/字符 的换算（技术方案 §7 实测口径）。**只有拿不到真分词器时**才用它估算。
TOKENS_PER_CHAR = 0.69

#: 句末标点：**只有这些能收口**
_SENTENCE_END = "。！？；.!?;…"  #: 含 **ASCII 句号**（英文文档全靠它；数字里的点由 `_inside_number` 挡掉）
#: 续句标点：只续不切；单句超预算时在这里退让
_CLAUSE_END = "，、：,:"
#: 子块下限的默认比例（占 child 上限）：太短的块不单独成块（**只在同一块内**生效）
_MIN_CHILD_RATIO = 0.4
#: 成对符号：内部不切（引号在后面单独处理，因为中英文引号方向不同）
_PAIRS = {"（": "）", "(": ")", "【": "】", "[": "]", "《": "》", "〈": "〉", "「": "」", "『": "』", "“": "”", "‘": "’"}
#: 可以成对也可单独出现的引号（按"配对着用"处理）
_QUOTES = "\"'"
#: 引号类成对符号：超预算长段落允许**忽略它们**切在逗号上（否则长篇对白会被当成一句）
_QUOTE_PAIRS = frozenset("“”‘’「」『』")
#: 收尾符号：句末标点后面跟着它们时一起算进这一句（"……完。" / "'……！'"）
_TRAILING = "）)】]》〉」』”’\"'"
