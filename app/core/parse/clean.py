"""不可见字符清洗（方案甲）：去掉"看不见但会坏事"的字符。

## 在流水线里的位置

- **上游**：各格式解析器（txt/pdf/docx/xlsx/pptx）产出的原始块文本；
- **本模块**：只做**字符级**清洗（删/归一），**不动行结构、不改语义、不切分**；
- **下游**：清洗后的文本进结构识别 → 切分 → 入库，同时进 ``text_hash`` 指纹。
  调用点是 :func:`app.core.parse.iter_units`（唯一出口），本模块不自己遍历文档。

## 输入输出

- 输入：一个块的原始文本（``str``，可能含 NUL/零宽/控制符）。
- 输出：清洗后的 ``str``（**可能更短**：删掉的字符不会补回来；不可见空格变成普通空格）；
  **不返回 None、不抛异常**（空串原样返回），调用方无需做防御性判断。

## 清洗什么、保留什么

| 处理 | 字符 |
| --- | --- |
| **去掉** | NUL（U+0000）· BOM/零宽不换行空格（U+FEFF，文件中间的残留）· 零宽空格（U+200B）· 词连接符（U+2060）· 软连字符（U+00AD）· C0/C1 控制符（`\x01-\x08`、`\x0b`、`\x0c`、`\x0e-\x1f`、`\x7f-\x9f`） |
| **归一** | 不换行空格（U+00A0）与窄不换行空格（U+202F）→ 普通空格（它们看不见，却会让"看起来一样"的两段文本匹配不上） |
| **保留** | `\t` `\n` `\r`（结构）· **ZWJ/ZWNJ（U+200D/U+200C）**：emoji 靠它们连起来、阿拉伯/波斯/天城文的字形也靠它们，删了就散架 · 方向标记（U+200E/U+200F）· 变体选择符（U+FE0E/U+FE0F）· 表意空格（U+3000，中文里是正常空格） |

## 为什么在解析层统一做（而不是各格式各做）

一份资料可能来自 txt/pdf/docx/xlsx/pptx——清洗散在五处必然漂移。放在
:func:`app.core.parse.iter_units` 这个**唯一出口**上，所有格式、所有入口（流式/整份/字节）
都过同一道关。

## 为什么必须同时清正文与索引

- 只在索引里清：`chunks.text` 里留着 NUL（将来任何按 C 字符串处理的环节都可能**在那儿截断**）；
- 只在正文里清：索引里留着零宽字符（分词噪声、匹配干扰）。
两处同源（都来自块文本），所以清一次就对两边都生效。

## 影响

清洗改变了正文 → `text_hash` 变了 → **同一份文件在本次改动前后会被当成两份内容**。
所以改动后建议做一次**全量重建**（`rebuild`），否则新旧资料会并存。
"""

from __future__ import annotations

import re

#: C0/C1 控制符（**不含** `\t`、`\n`、`\r`——它们是结构）
_CONTROL = re.compile(r"[\x01-\x08\x0b\x0c\x0e-\x1f\x7f-\x9f]")

#: 单个字符的"看不见的噪声"（逐字符替换，代价可忽略）
_INVISIBLE = ("\x00", "\ufeff", "\u200b", "\u2060", "\u00ad")

def compact_ws(text: str) -> str:
    """去掉**所有空白**（条款号/编号里常有排版空格："第 3 条" → "第3条"）。

    也用于"切分结果是否一字不差地拼回原文"的校验（比真正删空白更宽容些，
    排版空格本就不该参与字节级比较）。

    参数：
        text: 任意文本（可以是空串）。
    返回：
        删掉所有空白字符（含换行）的新串；空串返回空串。
    """
    return re.sub(r"\s+", "", text)

#: 不可见空格 → 普通空格
_SPACES = {"\u00a0": " ", "\u202f": " "}


def strip_invisible(text: str) -> str:
    """清掉不可见噪声（见模块说明）；空串原样返回。

    三步**有固定顺序**：

    1. 先删 C0/C1 控制符（正则一次过）；
    2. 再逐个删零宽类字符。用 ``in`` 先判断一下再 ``replace``，是为了在**绝大多数
       文本本来就没有**这些字符时不付出重建字符串的代价（``str`` 不可变，
       ``replace`` 每次都会新分配一份）；
    3. 最后把不可见空格换成普通空格（**归一化**，不是删除：两词之间要留分隔，
       删掉会粘成一个词）。

    第 2、3 步的字符集目前互不相交，先后其实不影响结果；但保持"先删后归一"的固定
    顺序，是为了以后往集合里加字符时不会出现"先被归一成普通字符、又被删掉"的意外。

    参数：
        text: 块的原始文本。
    返回：
        清洗后的串（没东西可清时返回等值串，不保证是新对象）。
    """
    if not text:
        return text
    cleaned = _CONTROL.sub("", text)
    for bad in _INVISIBLE:
        # 先 in 再 replace：这些字符在正常中文里几乎不出现，省掉整串重建
        if bad in cleaned:
            cleaned = cleaned.replace(bad, "")
    for source, target in _SPACES.items():
        if source in cleaned:
            cleaned = cleaned.replace(source, target)
    return cleaned
