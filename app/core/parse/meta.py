"""文章元信息的识别：日期 / 来源 / 作者 / 责任编辑（**各格式共用**）。

## 在流水线里的位置

- **上游**：各格式解析器（:mod:`app.core.parse.text` 的 html/txt/md、``docx``）在造块时调用；
- **本模块**：只回答"这段文本是不是文章元信息"，**不改文本、不抛异常**；
- **下游**：解析器据此**跳过**元信息块，避免"2026-10-18 08:40 来源：人民日报"成为
  第一个正文片段的开头（引用/检索里看着不像正文，实测）。

## 为什么单独一个模块

同一套判据要在 html / txt / md / docx 四处用。散着写必然漂移；放一处，
改阈值/加词只改这里。**解析器只负责调用，不各写一份正则。**

## 判据（宁少不多）

1. 短块（≤120 字）且**首行是日期**、同时含"来源/作者/责任编辑"等词；
2. 短块（≤40 字）且**整段以**"来源/作者/责任编辑"开头（没有日期的站点）。

正文里以年份开头的句子（"2026年，中国第三次…"）不同时含元信息词，不会被误删。
"""

from __future__ import annotations

import re

#: 文章元信息的**首行日期**（2026-10-18 / 2026/10/18 / 2026年10月18日，可带时间）
_DATE_HEAD = re.compile(r"^\s*\d{4}\s*[-/年]\s*\d{1,2}\s*[-/月]\s*\d{1,2}")
#: 出现这些词才把"日期块"认成元信息（避免误删正文里以年份开头的句子）
_META_WORDS = ("来源", "作者", "责任编辑", "发布时间", "发布日期")
#: 没有日期时，整段以这些词开头也算元信息
_META_PREFIXES = ("来源", "作者", "责任编辑")


def looks_like_article_meta(text: str) -> bool:
    """这段文本是不是**文章元信息**（日期 / 来源 / 责任编辑），不该进正文片段。

    为什么要单判：这类信息常和正文放在同一层 ``<div>`` / 同一个段落流里，会被当普通
    段落收进第一个 child——引用/检索里就出现"2026-10-18 08:40 来源：人民日报"开头的
    正文（实测）。

    判据**宁少不多**（两条命中其一即可）：

    1. 短块（≤120 字）且**首行是日期**、同时含"来源/作者/责任编辑"等词；
    2. 短块（≤40 字）且**整段以**"来源/作者/责任编辑"开头（没有日期的站点）。

    正文里以年份开头的句子（"2026年，中国第三次…"）不同时含元信息词，不会被误删。

    参数：
        text: 一个块的文本。
    返回：
        像文章元信息返回 True。
    """
    stripped = text.strip()
    if not stripped or len(stripped) > 120:
        return False
    first = stripped.split("\n", 1)[0].strip()
    if _DATE_HEAD.match(first) and any(word in stripped for word in _META_WORDS):
        return True
    return len(stripped) <= 40 and first.startswith(_META_PREFIXES)
