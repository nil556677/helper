"""第一个功能页面：聊天。

**结构借鉴 DSH 的 Chat**：

- 一轮 = **用户气泡 + 过程行（可收起）+ 答案（永不收起）**；
- 间距照它的规格：过程行之间 6px、答案与过程行 12px、引用行与答案 8px；
- 过程行文字默认 tertiary、悬停 secondary；
- 出处是**可以 Tab 到的按钮**，点开在右栏看片段全文（DSH 同样是"引用点开侧栏"）；
- 报错用语义色，和"没找到"不能长一样。

**等待反馈（DSH 的 running status 简化版）**：发消息后**立刻**画用户气泡 +
一条带微光的"正在求索中"行（跳动点 + 秒表），检索在后台线程跑，
界面不再"点了没反应"；完成后把这一行整体换成正式的一轮（过程组 + 答案）。
秒表用 ``ui.timer`` 推，等待行被替换时随元素一起取消（NiceGUI 的 timer
删除元素时自动 cancel）。

**发送队列（DSH 式）**：输入区始终可编辑、可发送。已有一条在检索时，新消息进入
输入框上方的**待发送队列**；队列项在**开始执行前**可编辑、可删除，当前一条完成后
自动逐条执行（队列项记住发送时的会话，切走后结果仍落回原会话）。
队列是**内存级**，上限见 :mod:`app.ui.state.chat_queue`（默认 10 条 / 10000 字符）；
满了**以先到的为准**，新消息拒绝并提示（输入框内容保留，方便改短再发）。

**工作步骤展示**：过程组固定用 DSH 的「标准」档——完成的一轮折起（标题是
步骤名 + 耗时），点开才看到**步骤明细**（图标 + 标题 + 明细，对应 DSH 的工具/
命令行）与**推理预览**（本地检索口径的理解与依据，不是模型思维链）。

**多会话**：内容属于"当前会话"（`app/state/conversations.py`）。切会话时这里整块重画；
发消息时**只增量画这一轮**——等待行有动画，整块重画会把动画抹掉。
检索期间切走了会话：结果落回**原会话**的数据（``conversations.append_to``），
不碰当前 DOM，回来后照样看得到这一轮。

**数据源**：`app/agent/stream.start_stream` → 父图/RAG 子图 → 事件流；本文件只渲染时间线与答案。

**底栏统计（DSH 的 composer dock 简化版）**：会话轮数/引用条数与上下文占用
（用户/回答/引用各自估成 token 的占比）见 `app/services/chat_stats.py`。"""

